#!/usr/bin/env node
/* ══════════════════════════════════════════════
   WHAT IS ACTUALLY IN THE CLIP POOL — and a config.json to start from.

     node server/clipper/scripts/list-games.js
     node server/clipper/scripts/list-games.js --days 365 --min-views 10
     node server/clipper/scripts/list-games.js --emit-config > server/clipper/config.json

   Needs only the Twitch credentials the site already has (TWITCH_CLIENT_ID,
   TWITCH_CLIENT_SECRET, TWITCH_BROADCASTER_ID). No Postgres, no Google, no
   TikTok — so this is runnable BEFORE the broadcaster has done anything.

   It answers the question config.json exists to answer: which games does this
   channel actually have clips for, how many, and what are their game ids. The
   ids are what routing keys on, and they are not guessable.

   --emit-config prints a complete config.json with one route per game, with
   credsEnv names derived from the game name. Review it, merge games that
   should share an account onto ONE route (that is how the per-account cap
   covers them together), delete the ones you do not want posted, then save it.
   ══════════════════════════════════════════════ */

import { findClips, resolveGames } from '../twitch.js';
import { memoryKv } from '../memory-kv.js';

const arg = (f, d) => { const i = process.argv.indexOf(f); return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : d; };
const emit = process.argv.includes('--emit-config');
const days = Number(arg('--days', '365'));
const minViews = Number(arg('--min-views', '0'));

const { bootEnv, serviceArg } = await import('../env-boot.js');
await bootEnv(serviceArg());

const env = { ...process.env, MARKETPLACE: memoryKv() };
for (const k of ['TWITCH_CLIENT_ID', 'TWITCH_CLIENT_SECRET', 'TWITCH_BROADCASTER_ID']) {
  if (!env[k]) { console.error(`\n✗ ${k} is not set. Run this where the site's env is available.\n`); process.exit(2); }
}

const clips = await findClips(env, { lookbackDays: days, minViews });
const names = await resolveGames(env, clips.map(c => c.gameId));

const byGame = new Map();
for (const c of clips) {
  const key = c.gameId || '(none)';
  const g = byGame.get(key) || { id: key, name: names.get(c.gameId) || '(uncategorised)', clips: 0, views: 0, top: null };
  g.clips++; g.views += c.views;
  if (!g.top || c.views > g.top.views) g.top = c;
  byGame.set(key, g);
}
const games = [...byGame.values()].sort((a, b) => b.clips - a.clips);

if (!emit) {
  console.log(`\nClip pool: ${clips.length} clips over ${days} days` +
    (minViews ? ` with >= ${minViews} views` : '') + `, across ${games.length} game(s).\n`);
  const pad = (s, n) => String(s).padEnd(n).slice(0, n);
  console.log(pad('GAME ID', 10) + pad('GAME', 34) + pad('CLIPS', 7) + pad('VIEWS', 8) + 'TOP CLIP');
  console.log('─'.repeat(100));
  for (const g of games) {
    console.log(pad(g.id, 10) + pad(g.name, 34) + pad(g.clips, 7) + pad(g.views, 8) +
      `${g.top.views}v  ${g.top.title.slice(0, 32)}`);
  }
  console.log(`\nRe-run with --emit-config to print a config.json scaffold.\n`);
  process.exit(0);
}

/* YT_MAGIC_THE_GATHERING from "Magic: The Gathering" */
const envName = (prefix, gameName) => prefix + '_' + String(gameName)
  .toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 28) || prefix + '_MAIN';
const tag = (gameName) => '#' + String(gameName).replace(/[^A-Za-z0-9]+/g, '');

const config = {
  _comment: 'Generated by list-games.js — REVIEW BEFORE USE. Merge games that should share an account onto one route so the per-account cap covers them together, and delete any game you do not want posted. Secrets are NOT here: set <credsEnv>_CLIENT_ID/_SECRET/_REFRESH_TOKEN (YouTube) and <credsEnv>_CLIENT_KEY/_SECRET/_REFRESH_TOKEN (TikTok) in the rig environment.',
  defaults: { lookbackDays: days, perAccount: 2, minViews: 10, maxDurationSec: 60, maxPerRun: 20 },
  routes: games.filter(g => g.id !== '(none)').map(g => ({
    label: g.name,
    match: { gameIds: [g.id], gameNames: [g.name] },
    hashtags: [tag(g.name), '#PhantomACE'],
    youtube: { credsEnv: envName('YT', g.name), privacy: 'public' },
    tiktok: { credsEnv: envName('TT', g.name), privacy: 'SELF_ONLY' },
  })),
  fallback: {
    label: 'PhantomACE',
    hashtags: ['#PhantomACE', '#Twitch'],
    youtube: { credsEnv: 'YT_MAIN', privacy: 'public' },
    tiktok: { credsEnv: 'TT_MAIN', privacy: 'SELF_ONLY' },
  },
};
console.log(JSON.stringify(config, null, 2));
